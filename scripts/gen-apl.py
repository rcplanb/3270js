#!/usr/bin/env python3
"""Generate src/core/codepage/apl.ts: IBM code page 310 (APL / Graphic Escape) to Unicode.

Usage: python3 -I scripts/gen-apl.py <x3270>/Common/unicode.c > src/core/codepage/apl.ts

Reads x3270's apl2uc[] table (the mapping x3270 displays GE characters with).
Mapping data: Copyright (c) 2008-2026 Paul Mattes, BSD-3-Clause (see
THIRD_PARTY_NOTICES.md). APL's underlined letters, which have no Unicode
equivalent, are shown as plain letters, as x3270 does by default.
"""
import re
import sys

src = open(sys.argv[1], encoding='latin-1').read()
m = re.search(r'static ucs4_t apl2uc\[256\] = \{(.*?)\};', src, re.S)
if not m:
    sys.exit('apl2uc[] not found')
values = [int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{4})', re.sub(r'/\*.*?\*/', '', m.group(1)))]
assert len(values) == 256, len(values)
table = {b: v for b, v in enumerate(values) if v}
# Underlined A-Z (x3270 apl_to_unicode "undera").
under = [*range(0x41, 0x4a), *range(0x51, 0x5a), *range(0x62, 0x6a)]
for i, b in enumerate(under):
    table.setdefault(b, ord('A') + i)

print('// Generated by scripts/gen-apl.py from x3270 (Common/unicode.c apl2uc[]).')
print('// Mapping data (c) 2008-2026 Paul Mattes, BSD-3-Clause; see THIRD_PARTY_NOTICES.md.')
print('// Do not edit.')
print()
print('/** IBM code page 310 (APL / Graphic Escape) byte to Unicode, for display. */')
print('export const CP310: ReadonlyMap<number, string> = new Map([')
for b in sorted(table):
    print(f"  [0x{b:02x}, '\\u{{{table[b]:x}}}'],")
print(']);')
