#!/usr/bin/env python3
"""Generate src/renderer/oia-glyphs.ts from x3270's 20-point BDF font.

Usage: python3 -I scripts/gen-oia-glyphs.py <x3270>/x3270/3270-20.bdf > src/renderer/oia-glyphs.ts

Each glyph becomes an SVG path in a 10x20 cell (one rectangle per run of
lit pixels), usable as inline SVG and as a canvas Path2D. Glyph data:
Copyright (c) 1995-2009 Paul Mattes, BSD-3-Clause (see THIRD_PARTY_NOTICES.md).
"""
import sys

# x3270 glyph name -> our name.
GLYPHS = {
    'box4': 'box4', 'underA': 'underA', 'underB': 'underB', 'boxsolid': 'boxSolid',
    'boxquestion': 'boxQuestion', 'boxhuman': 'boxHuman', 'lock': 'lock',
    'clockleft': 'clockLeft', 'clockright': 'clockRight', 'human': 'human',
    'leftarrow': 'leftArrow', 'rightarrow': 'rightArrow', 'commhi': 'commHi',
    'commlo': 'commLo', 'commjag': 'commJag', 'badcommhi': 'badCommHi',
    'keyleft': 'keyLeft', 'keyright': 'keyRight', 'upshift': 'upShift',
    'downshift': 'downShift', 'insert': 'insert',
}

lines = open(sys.argv[1], encoding='latin-1').read().split('\n')
fbb = None
glyphs = {}
i = 0
while i < len(lines):
    l = lines[i]
    if l.startswith('FONTBOUNDINGBOX'):
        fbb = list(map(int, l.split()[1:]))
    elif l.startswith('STARTCHAR'):
        name = l.split()[1]
    elif l.startswith('BBX'):
        bbx = list(map(int, l.split()[1:]))
    elif l == 'BITMAP':
        rows = []
        i += 1
        while lines[i] != 'ENDCHAR':
            rows.append(int(lines[i], 16))
            i += 1
        glyphs[name] = (bbx, rows, ((bbx[0] + 7) // 8) * 8)
    i += 1

FW, FH, FX, FY = fbb
assert (FW, FH) == (10, 20), fbb


def path(name):
    (w, h, xo, yo), rows, bits = glyphs[name]
    top = (FH + FY) - (h + yo)
    d = []
    for r, v in enumerate(rows):
        c = 0
        while c < w:
            if v >> (bits - 1 - c) & 1:
                start = c
                while c < w and v >> (bits - 1 - c) & 1:
                    c += 1
                d.append(f'M{start + xo - FX} {top + r}h{c - start}v1h-{c - start}z')
            else:
                c += 1
    return ''.join(d)


print('// Generated by scripts/gen-oia-glyphs.py from x3270\'s 3270-20.bdf. Do not edit.')
print('// Glyph data: Copyright (c) 1995-2009 Paul Mattes; BSD-3-Clause (THIRD_PARTY_NOTICES.md).')
print()
print('/** Status-line glyphs as SVG paths in a 10x20 cell. */')
print('export const OIA_GLYPH_SIZE = { width: 10, height: 20 } as const;')
print()
print('export const OIA_GLYPHS = {')
for x, ours in GLYPHS.items():
    print(f"  {ours}: '{path(x)}',")
print('} as const;')
print()
print('export type OiaGlyph = keyof typeof OIA_GLYPHS;')
