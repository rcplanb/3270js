#!/usr/bin/env python3
"""Generate an EBCDIC code page table module from Python's codec.

Usage: python3 -I scripts/gen-codepage.py cp037 "IBM-037 (US/Canada)" 037 ibm-037 \
         > src/core/codepage/cp037.ts

Python's EBCDIC codecs are generated from the Unicode Consortium mapping
files. For cp037 this was cross-checked byte-for-byte against
unicode.org/Public/MAPPINGS/VENDORS/MICSFT/EBCDIC/CP037.TXT (no differences).
"""
import sys

codec, name, *aliases = sys.argv[1:]
chars = [bytes([b]).decode(codec) for b in range(256)]
assert len(set(chars)) == 256, "code page is not a bijection"


def esc(c: str) -> str:
    o = ord(c)
    if c in "'\\" or o < 0x20 or 0x7F <= o <= 0xA0 or o == 0xAD:
        return f"\\u{o:04x}"
    return c


var = codec.replace("-", "_")
print("// Generated by scripts/gen-codepage.py from Python's '%s' codec. Do not edit." % codec)
print("import { createCodePage } from './codepage.js';")
print()
print("/** %s. */" % name)
print("export const %s = createCodePage({" % var)
print("  id: '%s'," % codec)
print("  name: '%s'," % name)
print("  aliases: [%s]," % ", ".join(f"'{a}'" for a in aliases))
print("  // prettier-ignore")
print("  table:")
rows = []
for hi in range(16):
    row = "".join(esc(chars[hi * 16 + lo]) for lo in range(16))
    rows.append(f"    '{row}' + // {hi:X}0-{hi:X}F")
rows[-1] = rows[-1].replace(" + //", ", //")
print("\n".join(rows))
print("});")
