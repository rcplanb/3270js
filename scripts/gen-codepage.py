#!/usr/bin/env python3
"""Generate an EBCDIC code page table module.

Usage:
  python3 -I scripts/gen-codepage.py SOURCE ID NAME GCSGID,CPGID [ALIAS...] > src/core/codepage/ID.ts

SOURCE is a Python codec name (cp037, cp500, cp1140) or the path of an ICU
.ucm mapping file (ibm-1047_P100-1995.ucm, ibm-285_P100-1995.ucm from
github.com/unicode-org/icu, icu4c/source/data/mappings), used for code pages
Python lacks. Only round-trip (|0) mappings are read from a .ucm file.

GCSGID,CPGID is the code page's CGCSGID, reported to the host in the Query
Reply (Character Sets), as x3270 reports it.

Cross-checks (2026-11-22), all identical over all 256 bytes unless noted:
- cp037:  Python = ICU ibm-37 = unicode.org CP037.TXT
- cp500:  Python = ICU ibm-500 = unicode.org CP500.TXT
- cp1140: Python = ICU ibm-1140 (cp037 with the euro at X'9F')
- cp1047, cp285: ICU = x3270's tables (graphic range X'41'-X'FE')
- cp500, cp1140: also = x3270's tables
"""
import re
import sys

source, cp_id, name, cgcsgid, *aliases = sys.argv[1:]
gcsgid, cpgid = (int(v) for v in cgcsgid.split(","))

if source.endswith(".ucm"):
    table = {}
    for line in open(source, encoding="latin-1"):
        m = re.match(r"<U([0-9A-F]{4})>\s+\\x([0-9A-F]{2})\s+\|0", line)
        if m:
            table[int(m.group(2), 16)] = chr(int(m.group(1), 16))
    assert len(table) == 256, f"{source}: {len(table)} round-trip mappings, expected 256"
    chars = [table[b] for b in range(256)]
    origin = f"ICU's {source.rsplit('/', 1)[-1]}"
else:
    chars = [bytes([b]).decode(source) for b in range(256)]
    origin = f"Python's '{source}' codec"
assert len(set(chars)) == 256, "code page is not a bijection"


def esc(c: str) -> str:
    o = ord(c)
    if c in "'\\" or o < 0x20 or 0x7F <= o <= 0xA0 or o == 0xAD:
        return f"\\u{o:04x}"
    return c


print(f"// Generated by scripts/gen-codepage.py from {origin}. Do not edit.")
print("import { createCodePage } from './codepage.js';")
print()
print("/** %s. */" % name)
print("export const %s = createCodePage({" % cp_id)
print("  id: '%s'," % cp_id)
print("  name: '%s'," % name)
print("  aliases: [%s]," % ", ".join(f"'{a}'" for a in aliases))
print("  cgcsgid: [%d, %d]," % (gcsgid, cpgid))
print("  // prettier-ignore")
print("  table:")
rows = []
for hi in range(16):
    row = "".join(esc(chars[hi * 16 + lo]) for lo in range(16))
    rows.append(f"    '{row}' + // {hi:X}0-{hi:X}F")
rows[-1] = rows[-1].replace(" + //", ", //")
print("\n".join(rows))
print("});")
